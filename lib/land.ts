function inside(x: number, y: number, poly: P): boolean {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}

export const MAP = { cols: 90, rows: 36, lon0: -170, lon1: 180, lat0: 80, lat1: -58 };

export function project(lon: number, lat: number) {
  return {
    x: (lon - MAP.lon0) / (MAP.lon1 - MAP.lon0),
    y: (MAP.lat0 - lat) / (MAP.lat0 - MAP.lat1),
  };
}

let cache: boolean[] | null = null;
export function landMask(): boolean[] {
  if (cache) return cache;
  const out: boolean[] = new Array(MAP.cols * MAP.rows);
  for (let r = 0; r < MAP.rows; r++) {
    for (let c = 0; c < MAP.cols; c++) {
      const lon = MAP.lon0 + ((c + 0.5) / MAP.cols) * (MAP.lon1 - MAP.lon0);
      const lat = MAP.lat0 - ((r + 0.5) / MAP.rows) * (MAP.lat0 - MAP.lat1);
      let land =
        inside(lon, lat, EURASIA) ||
        inside(lon, lat, AFRICA) ||
        inside(lon, lat, NORTH_AMERICA) ||
        inside(lon, lat, SOUTH_AMERICA) ||
        inside(lon, lat, GREENLAND) ||
        inside(lon, lat, AUSTRALIA) ||
        ISLANDS.some((isl) => inside(lon, lat, isl));
      if (
        land &&
        (inside(lon, lat, BLACK_SEA) ||
          inside(lon, lat, CASPIAN) ||
          inside(lon, lat, HUDSON_BAY) ||
          inside(lon, lat, GREAT_LAKES))
      ) {
        land = false;
      }
      out[r * MAP.cols + c] = land;
    }
  }
  return (cache = out);
}
